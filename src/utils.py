# pictures:
def get_picture_by_url(image_url):
    response = requests.get(image_url)
    response.raise_for_status()
    if response.status_code != 200:
        log(f'Failed to fetch image: {response.status_code} - {response.text}', no_silent=False)
    return response.content

async def fetch_image_bytes(url):
    async with aiohttp.ClientSession() as session:
        async with session.get(url) as response:
            response.raise_for_status()
            if response.status != 200:
                log(f'Failed to fetch image bytes: {response.status} - {response.text}', no_silent=False)
            return await response.read()

