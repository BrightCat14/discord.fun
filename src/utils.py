# pictures:
def get_picture_by_url(image_url):
    response = requests.get(image_url)
    response.raise_for_status()
    if response.status_code != 200:
        log(
            f"Failed to fetch image: {response.status_code} - {response.text}",
            no_silent=False,
        )
    return response.content


async def fetch_image_bytes(url):
    async with aiohttp.ClientSession() as session:
        async with session.get(url) as response:
            response.raise_for_status()
            if response.status != 200:
                log(
                    f"Failed to fetch image bytes: {response.status} - {response.text}",
                    no_silent=False,
                )
            return await response.read()


def __init():
    global plugins_globals
    sys.path.append(plugin_dir)

    log("Initializing", no_silent=False)

    # creating dirs
    if not os.path.exists(app_path):
        os.mkdir(app_path)
    if not os.path.exists(plugin_dir):
        os.mkdir(plugin_dir)

    # creating cfgs
    if not os.path.exists(theme_cfg):
        with open(theme_cfg, "w") as f:
            f.write("kali-old")
    if not os.path.exists(custom_prompt_path):
        with open(custom_prompt_path, "w") as f:
            f.write("$")

    # loading plugins
    plugins.load_plugins()
    plugins_globals.update(plugins.plugins)
    log(f"Loaded plugins {plugins.get_plugins()}", no_silent=False)
    atexit.register(plugins.exit_plugins)

    cli.set_console_title(constants.title)


# logs
def log(*args, no_silent=True, **kwargs):
    if no_silent:
        print(*args, **kwargs)
    end = kwargs.get("end", "\n")
    timestamp = datetime.now().strftime("[%Y-%m-%d %H:%M:%S] ")
    if args:
        s = timestamp + " ".join(map(str, args)) + end
    else:
        s = timestamp + "[empty log call]" + end
    with open(log_path, "a", encoding="utf-8") as f:
        f.write(s)


# prompts util
def parse_custom_prompt(custom_prompt="$"):
    result = ""
    i = 0
    while i < len(custom_prompt):
        if custom_prompt[i] == "{" and "}" in custom_prompt[i:]:
            j = custom_prompt.index("}", i)
            key = str(custom_prompt[i + 1 : j].lower())
            if key.startswith("eval(") and key.endswith(")"):
                eval_content = key[5:-1]
                eval_content = eval_content[1:-1]
                try:
                    value = eval(eval_content, plugins_globals)
                except Exception as e:
                    log(f"Failed to evaluate custom prompt: {e}", no_silent=True)
                    value = "Error"
                result += str(value)
            elif key in REPLACEMENTS:
                result += REPLACEMENTS[key]
            else:
                result += "{" + key + "}"
            i = j + 1
        else:
            result += custom_prompt[i]
            i += 1
    return result + tabber.space()
